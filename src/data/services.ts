export const serviceBySlug = (slug: string): Service | undefined =>
  SERVICES.find((s) => s.slug === slug);

export const servicesByCategory = (category: ServiceCategory): Service[] =>
  SERVICES.filter((s) => s.category === category);

export const relatedServices = (service: Service): Service[] =>
  service.related
    .map((slug) => serviceBySlug(slug))
    .filter((s): s is Service => Boolean(s))
    .slice(0, 4);

export const techNames = (service: Service): string[] =>
  service.technologies.map((t) => t.name);

export const primaryTech = (service: Service, count = 4): { shown: string[]; extra: number } => {
  const names = techNames(service);
  return { shown: names.slice(0, count), extra: Math.max(0, names.length - count) };
};

export const techGroups = (service: Service): { group: string; items: ServiceTech[] }[] => {
  const groups: { group: string; items: ServiceTech[] }[] = [];
  for (const tech of service.technologies) {
    const existing = groups.find((g) => g.group === tech.category);
    if (existing) existing.items.push(tech);
    else groups.push({ group: tech.category, items: [tech] });
  }
  return groups;
};
