export const industryBySlug = (slug: string): Industry | undefined =>
  INDUSTRIES.find((i) => i.slug === slug);

export const relatedIndustries = (industry: Industry): Industry[] =>
  industry.related
    .map((slug) => industryBySlug(slug))
    .filter((i): i is Industry => Boolean(i))
    .slice(0, 4);

export const industryTechGroups = (industry: Industry): { group: string; items: IndustryTech[] }[] => {
  const groups: { group: string; items: IndustryTech[] }[] = [];
  for (const t of industry.technologies) {
    const existing = groups.find((g) => g.group === t.category);
    if (existing) existing.items.push(t);
    else groups.push({ group: t.category, items: [t] });
  }
  return groups;
};
